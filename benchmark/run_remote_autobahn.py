def run_nodes(node_conns: Dict[str, Connection], repeat_num: int, wd: str, num_workers: int) -> List:
    promises = []
    
    for node_num, (node, conn) in enumerate(node_conns.items()):
        binary_name = f"./target/release/server_{node}"
        cmd = CommandMaker.run_primary(
            PathMaker.key_file(node_num, path_prefix="configs/"),
            PathMaker.committee_file(path_prefix="configs/"),
            PathMaker.db_path(node_num, path_prefix=""),
            PathMaker.parameters_file(path_prefix="configs/"),
            debug=False,
            binary_name=binary_name
        )
        # Log parser expects primary logs to start with primary-
        prom = conn.run(f"cd pft/{wd} && {cmd} > logs/{repeat_num}/primary-{node}.err 2> logs/{repeat_num}/primary-{node}.log",
                    pty=True, asynchronous=True, hide=True)
        promises.append(prom)

        for worker_num in range(num_workers):
            cmd = CommandMaker.run_worker(
                    PathMaker.key_file(node_num, path_prefix="configs/"),
                    PathMaker.committee_file(path_prefix="configs/"),
                    PathMaker.db_path(node_num, worker_num),
                    PathMaker.parameters_file(path_prefix="configs/"),
                    worker_num,
                    debug=False,
                    binary_name=binary_name
                )
            # Log parser expects primary logs to start with worker-
            prom = conn.run(f"cd pft/{wd} && {cmd} > logs/{repeat_num}/worker-{node}-{worker_num}.err 2> logs/{repeat_num}/worker-{node}-{worker_num}.log",
                    pty=True, asynchronous=True, hide=True)
            promises.append(prom)

    return promises

def run_nodes_with_net_perf(node_conns: Dict[str, Connection], repeat_num: int, wd: str, payload_sz = 4096) -> List:
    promises = []
    
